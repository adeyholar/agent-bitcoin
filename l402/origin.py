class OriginHandler(BaseHTTPRequestHandler):
    def _send(self, status: int, content_type: str, raw: bytes) -> None:
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        if content_type == "application/pdf":
            name = (
                "l402-script.pdf"
                if "script.pdf" in self.path.split("?", 1)[0]
                else "l402-demo-report.pdf"
            )
            self.send_header("Content-Disposition", f'attachment; filename="{name}"')
        elif content_type == "image/png":
            self.send_header(
                "Content-Disposition", 'attachment; filename="l402-demo-badge.png"'
            )
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def do_GET(self) -> None:  # noqa: N802
        status, content_type, raw = dispatch(self.path, method="GET")
        self._send(status, content_type, raw)

    def do_POST(self) -> None:  # noqa: N802
        try:
            length = int(self.headers.get("Content-Length") or "0")
        except ValueError:
            length = 0
        if length < 0:
            length = 0
        if length > 65_536:
            err = json.dumps({"ok": False, "error": "bad_input"}).encode("utf-8")
            self._send(400, "application/json", err)
            return
        raw_body = self.rfile.read(length) if length else b""
        status, content_type, raw = dispatch(self.path, method="POST", body=raw_body)
        self._send(status, content_type, raw)

    def log_message(self, fmt: str, *args: object) -> None:
        sys_stderr = __import__("sys").stderr
        sys_stderr.write("%s - %s\n" % (self.address_string(), fmt % args))


def main() -> None:
    host = os.environ.get("L402_ORIGIN_HOST", "0.0.0.0")
    port = int(os.environ.get("L402_ORIGIN_PORT", "8090"))
    httpd = ThreadingHTTPServer((host, port), OriginHandler)
    print(f"l402 origin listening on {host}:{port}", flush=True)
    httpd.serve_forever()


